package dev.huff.hexaquot.game;

import com.fasterxml.jackson.databind.node.ObjectNode;
import dev.huff.hexaquot.game.hexatrap.HexatrapFixtures;
import dev.huff.hexaquot.persistence.HexatrapCaseEntity;
import dev.huff.hexaquot.persistence.HexatrapGenerationAttemptEntity;
import io.quarkus.narayana.jta.QuarkusTransaction;
import io.quarkus.test.common.QuarkusTestResource;
import io.quarkus.test.junit.QuarkusTest;
import jakarta.inject.Inject;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

@QuarkusTest
@QuarkusTestResource(value = FakeHexatrapAgent.class, restrictToAnnotatedClass = true)
class HexatrapCaseGeneratorTest {
    @Inject HexatrapCaseGenerator generator;
    @Inject HexatrapCaseStore store;

    @BeforeEach
    void reset() {
        FakeHexatrapAgent.reset();
    }

    private static ObjectNode valid() {
        return HexatrapFixtures.lanternaJson();
    }

    private static ObjectNode wrongLiar() {
        ObjectNode draft = HexatrapFixtures.lanternaJson();
        ((ObjectNode) draft.path("solution")).put("liar", "A");
        return draft;
    }

    private List<HexatrapGenerationAttemptEntity> attempts(String date) {
        return QuarkusTransaction.requiringNew().call(() ->
            HexatrapGenerationAttemptEntity.<HexatrapGenerationAttemptEntity>list("puzzleDate = ?1 order by createdAt, attempt", date));
    }

    private HexatrapCaseEntity entity(String date) {
        return QuarkusTransaction.requiringNew().call(() -> HexatrapCaseEntity.<HexatrapCaseEntity>findById(date));
    }

    @Test
    void repairsAnInvalidDraftWithTheValidatorsFeedback() {
        String date = "2031-03-03"; // a Monday: difficulty 1
        FakeHexatrapAgent.DRAFTS.add(wrongLiar());
        FakeHexatrapAgent.DRAFTS.add(valid());

        assertEquals(HexatrapCaseGenerator.Outcome.READY, generator.generate(date, false));

        var second = FakeHexatrapAgent.DRAFT_REQUESTS.get(1);
        assertTrue(second.path("previousDraft").isObject());
        assertTrue(FakeHexatrapAgent.feedbackOf(second).stream().anyMatch(m -> m.contains("non rispetta il suo ruolo")), second.toString());
        var first = FakeHexatrapAgent.DRAFT_REQUESTS.get(0);
        assertEquals(1, first.path("brief").path("difficulty").asInt());
        assertEquals(60, first.path("brief").path("budget").asInt());
        assertTrue(first.path("previousDraft").isNull());

        var ready = store.ready(date).orElseThrow();
        assertEquals("La lanterna spenta di Capo Nero", ready.definition().title());
        assertEquals(10, ready.metrics().certificateCost());
        var entity = entity(date);
        assertEquals("READY", entity.status);
        assertEquals("openai/gpt-6-luna", entity.model);
        // The fixture is easy for a Monday's band only by a soft margin: it is accepted with its warning.
        assertTrue(entity.warningsJson.contains("par esperto"));
        var phases = attempts(date).stream().map(a -> a.phase + ":" + a.ok).toList();
        assertTrue(phases.containsAll(List.of("VALIDATE:false", "VALIDATE:true", "AUDIT:true", "ACCEPTED:true")), phases.toString());
        // Every audit request carries the texts, never the formulas.
        assertFalse(FakeHexatrapAgent.AUDIT_REQUESTS.get(0).toString().contains("formula"));

        // A ready case is never regenerated by the scheduler.
        assertEquals(HexatrapCaseGenerator.Outcome.SKIPPED, generator.generate(date, false));
    }

    @Test
    void sendsBackSentencesThatDoNotSayWhatTheirFormulaSays() {
        String date = "2031-03-08"; // a Saturday
        FakeHexatrapAgent.DRAFTS.add(valid());
        FakeHexatrapAgent.DRAFTS.add(valid());
        FakeHexatrapAgent.GARBLED.add("s_livia_cane");

        assertEquals(HexatrapCaseGenerator.Outcome.READY, generator.generate(date, false));

        var feedback = FakeHexatrapAgent.feedbackOf(FakeHexatrapAgent.DRAFT_REQUESTS.get(1));
        assertTrue(feedback.stream().anyMatch(m -> m.contains("s_livia_cane") && m.contains("non dice la stessa cosa")), feedback.toString());
        assertTrue(attempts(date).stream().anyMatch(a -> a.phase.equals("AUDIT") && !a.ok));
    }

    @Test
    void marksTheDateFailedWhenNoAttemptSucceedsAndAllowsARetry() {
        String date = "2031-03-05";
        FakeHexatrapAgent.DRAFTS.add(wrongLiar());

        assertEquals(HexatrapCaseGenerator.Outcome.FAILED, generator.generate(date, false));
        var entity = entity(date);
        assertEquals("FAILED", entity.status);
        assertNotNull(entity.lastError);
        assertEquals(3, entity.attempts);
        assertTrue(store.ready(date).isEmpty());

        FakeHexatrapAgent.DRAFTS.add(valid());
        FakeHexatrapAgent.DRAFTS.add(valid());
        FakeHexatrapAgent.DRAFTS.add(valid());
        assertEquals(HexatrapCaseGenerator.Outcome.READY, generator.generate(date, false));
        assertEquals("READY", entity(date).status);
    }

    @Test
    void regeneratesAReadyCaseOnlyWhenAsked() {
        String date = "2031-03-06";
        FakeHexatrapAgent.DRAFTS.add(valid());
        assertEquals(HexatrapCaseGenerator.Outcome.READY, generator.generate(date, false));
        String firstGeneration = entity(date).generatedAt;

        // A failed regeneration keeps the previous ready case.
        assertEquals(HexatrapCaseGenerator.Outcome.FAILED, generator.generate(date, true));
        assertEquals("READY", entity(date).status);
        assertEquals(firstGeneration, entity(date).generatedAt);
        assertTrue(store.ready(date).isPresent());
    }
}
